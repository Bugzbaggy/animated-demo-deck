// Builds deck/fonts.css with the fonts embedded as base64, so the deck works offline
// and from file:// (Chrome blocks file-to-file web font loads).
// Usage: node tools/fetch-fonts.mjs
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'deck', 'fonts.css');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const families = [
  'Inter:wght@400..800',
  'JetBrains+Mono:wght@400..700',
  'Lato:wght@400;700;900',
];

let css = '/* Generated by tools/fetch-fonts.mjs. Fonts: Inter, JetBrains Mono, Lato (SIL OFL 1.1). */\n';
for (const fam of families) {
  const res = await fetch(`https://fonts.googleapis.com/css2?family=${fam}&display=block`, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${fam}: HTTP ${res.status}`);
  const text = await res.text();
  // Keep only the latin subset blocks.
  const blocks = text.split('/* ').filter(b => b.startsWith('latin */'));
  if (!blocks.length) throw new Error(`${fam}: no latin block`);
  for (const b of blocks) {
    const face = b.slice(b.indexOf('@font-face'));
    const url = face.match(/url\((https:[^)]+)\)/)[1];
    const font = Buffer.from(await (await fetch(url)).arrayBuffer());
    css += face.replace(url, `data:font/woff2;base64,${font.toString('base64')}`).trim() + '\n';
    console.log(`${fam}: ${(font.length / 1024).toFixed(0)} KB`);
  }
}
await writeFile(out, css);
console.log(`wrote ${out} (${(css.length / 1024).toFixed(0)} KB)`);
